"""Wake idle app conversations from the durable coordination inbox.

Claim before submitting a provider turn. An uncertain submission is never
retried automatically, including after a runtime restart.
"""
from __future__ import annotations

import logging
import json
import os
import sqlite3
import threading
from datetime import datetime
from pathlib import Path

from .workspaces import matches_workspace
from .app_agent_failures import notify_agent_failure
from .store import CoordinationError
from .browser_persistence import database_busy


WAKE_PROMPT = ("[Automatic Agent Coord inbox wake — not a human message]\n"
               "Check and handle your unread agent-coord messages. "
               "This prompt was generated by the runtime because agent messages are pending.")
PRE_SUBMIT_RETRY_DELAYS = (5, 30)


class BrowserInboxWake:
    def __init__(self, sessions):
        self.sessions = sessions
        self.store = sessions.store
        self.stopped = threading.Event()
        self.worker = None
        self.checked_pauses = {}
        with self.store._connection() as db:
            db.execute("""CREATE TABLE IF NOT EXISTS browser_inbox_wake (
                thread_id TEXT PRIMARY KEY, paused INTEGER NOT NULL DEFAULT 0,
                dispatching INTEGER NOT NULL DEFAULT 0, error TEXT
            )""")
            db.execute("BEGIN IMMEDIATE")
            columns = {row[1] for row in db.execute("PRAGMA table_info(browser_inbox_wake)")}
            for column in ("pause_kind", "recovery_turn_id", "reconciled_turn_id"):
                if column not in columns:
                    db.execute(f"ALTER TABLE browser_inbox_wake ADD COLUMN {column} TEXT")
            for column, definition in (("retry_count", "INTEGER NOT NULL DEFAULT 0"),
                                       ("retry_at", "REAL"), ("paused_at", "REAL"),
                                       ("recovery_after_message_id", "INTEGER NOT NULL DEFAULT 0")):
                if column not in columns:
                    db.execute(f"ALTER TABLE browser_inbox_wake ADD COLUMN {column} {definition}")

            db.execute("""CREATE TABLE IF NOT EXISTS browser_wake_recoveries (
                id INTEGER PRIMARY KEY, thread_id TEXT NOT NULL, turn_id TEXT NOT NULL,
                requester TEXT NOT NULL, reason TEXT NOT NULL, pause_kind TEXT NOT NULL,
                recovered_at REAL NOT NULL, execution_confirmed INTEGER NOT NULL DEFAULT 0
            )""")
            if "execution_confirmed" not in {row[1] for row in db.execute("PRAGMA table_info(browser_wake_recoveries)")}:
                db.execute("ALTER TABLE browser_wake_recoveries ADD COLUMN execution_confirmed INTEGER NOT NULL DEFAULT 0")

    def pause(self, thread_id, reason, *, kind="unknown"):
        self.checked_pauses.pop(thread_id, None)
        with self.store._connection() as db:
            db.execute("""INSERT INTO browser_inbox_wake (thread_id, paused, error, pause_kind)
                VALUES (?, 1, ?, ?) ON CONFLICT(thread_id) DO UPDATE SET paused = 1,
                error = CASE WHEN pause_kind = 'stop' THEN error ELSE excluded.error END,
                pause_kind = CASE WHEN pause_kind = 'stop' THEN 'stop' ELSE excluded.pause_kind END,
                recovery_turn_id = NULL, reconciled_turn_id = NULL,
                recovery_after_message_id = 0""", (thread_id, reason, kind))
            db.execute("UPDATE browser_inbox_wake SET paused_at = COALESCE(paused_at, ?), retry_at = NULL WHERE thread_id = ?",
                       (self.store.clock(), thread_id))

    def resume(self, thread_id, *, preserve_capacity=False):
        """Accepted user input re-enables wakes, including after deliberate Stop."""
        self.checked_pauses.pop(thread_id, None)
        with self.store._connection() as db:
            db.execute("""UPDATE browser_inbox_wake SET paused = 0, dispatching = 0,
                error = NULL, pause_kind = NULL, recovery_turn_id = NULL,
                retry_count = 0, retry_at = NULL, paused_at = NULL,
                reconciled_turn_id = NULL, recovery_after_message_id = 0 WHERE thread_id = ?
                AND (? = 0 OR pause_kind IS NOT 'capacity_retry')""",
                       (thread_id, int(preserve_capacity)))

    def _not_submitted(self, thread_id, error):
        """Retry only transient contention proven to precede turn submission."""
        transient = isinstance(error, sqlite3.OperationalError) and database_busy(error)
        with self.store._connection() as db:
            db.execute("BEGIN IMMEDIATE")
            db.execute("INSERT OR IGNORE INTO browser_inbox_wake(thread_id) VALUES (?)", (thread_id,))
            row = db.execute("SELECT retry_count, pause_kind FROM browser_inbox_wake WHERE thread_id = ?", (thread_id,)).fetchone()
            if row["pause_kind"] == "stop":
                return
            count = row["retry_count"]
            retry_at = (self.store.clock() + PRE_SUBMIT_RETRY_DELAYS[count]
                        if transient and count < len(PRE_SUBMIT_RETRY_DELAYS) else None)
            db.execute("""UPDATE browser_inbox_wake SET retry_count = retry_count + 1,
                retry_at = ?, error = ?, pause_kind = 'pre_submit', paused = ?,
                paused_at = CASE WHEN ? IS NULL THEN ? ELSE NULL END WHERE thread_id = ?""",
                (retry_at, str(error), int(retry_at is None), retry_at, self.store.clock(), thread_id))
        if retry_at is None:
            self._report_failure(thread_id, "Inbox wake was not submitted. " + str(error))

    def _reconcile_pause(self, thread_id):
        """Bounded reads check a typed failure against provider history.

        Stop, an uncertain submission and a crashed claim remain untouched.
        Completion proof corrects the record, never authorizes queued work.
        """
        checked, next_check = self.checked_pauses.get(thread_id, (0, 0))
        if checked >= 3 or next_check > self.store.clock():
            return
        with self.store._connection() as db:
            row = db.execute("SELECT * FROM browser_inbox_wake WHERE thread_id = ?", (thread_id,)).fetchone()
        if (not row or not row["paused"] or row["pause_kind"] != "failure"
                or row["dispatching"] or row["reconciled_turn_id"]):
            return
        if self.store.threads.get(thread_id, history=False)["attention"] == "archived":
            return
        with self.store._connection() as db:
            if db.execute("SELECT 1 FROM sqlite_master WHERE name = 'thread_close_requests'").fetchone() and db.execute(
                    "SELECT 1 FROM thread_close_requests WHERE thread_id = ? AND status IN ('queued', 'closing')", (thread_id,)).fetchone():
                return
        detail = self.sessions.read(thread_id)
        self.checked_pauses[thread_id] = (checked + 1, self.store.clock() + (5 if checked == 0 else 30))
        latest = next(reversed(detail["thread"].get("turns", [])), {})
        current = self.store.threads.get(thread_id, history=False)
        if not detail["running"] and latest.get("id") == current["turn_id"]:
            latest = self._native_claude_completion(thread_id, latest, current) or latest
        if (detail["running"] or latest.get("status") != "completed"
                or latest.get("id") != current["turn_id"]):
            return
        with self.sessions.lock:
            history = self.sessions._history(thread_id)
            for index, saved in enumerate(history.get("turns", [])):
                if saved.get("id") == latest.get("id"):
                    history["turns"][index] = latest
                    self.sessions._save_history(thread_id)
                    break
        if not self.sessions.persistence.flush():
            self.checked_pauses.pop(thread_id, None)
            return
        with self.store._connection() as db:
            db.execute("BEGIN IMMEDIATE")
            # A late authoritative completion corrects the receipt, retaining
            # its identity so subscriptions and user acknowledgement stay valid.
            db.execute("""UPDATE turn_completions SET status = 'completed'
                WHERE thread_id = ? AND turn_key = ? AND status = 'failed'""", (thread_id, current["turn_key"]))
            db.execute("""UPDATE browser_inbox_wake SET reconciled_turn_id = ?,
                error = 'The previous turn completed; historical inbox work remains paused. Review it and send fresh instructions before explicit recovery. Earlier messages are retained as context.',
                recovery_after_message_id = (SELECT COALESCE(MAX(id), 0) FROM messages WHERE recipient_session_id = ?)
                WHERE thread_id = ? AND paused = 1 AND pause_kind = 'failure' AND dispatching = 0""",
                (latest["id"], thread_id, thread_id))
            if db.execute("SELECT 1 FROM sqlite_master WHERE name = 'app_agent_followups'").fetchone():
                db.execute("""UPDATE app_agent_followups SET resolved_at = ?, resolution = 'native_completion'
                    WHERE thread_id = ? AND turn_id = ? AND resolved_at IS NULL""",
                    (self.store.clock(), thread_id, latest["id"]))

    def _native_claude_completion(self, thread_id, turn, current):
        """Repair the old false-disconnect incident only with native end proof.

        A matching prompt, final end_turn, and successful Stop hook must be the
        latest native work, after this exact turn started. No provider is run.
        """
        if self.sessions._record(thread_id)["client"] != "claude" or turn.get("status") != "failed":
            return None
        error = turn.get("error") or ""
        if isinstance(error, dict):
            error = error.get("message", "")
        if "Claude Code disconnected" not in error:
            return None
        from .claude_usage import native_id
        import uuid
        try:
            identity = str(uuid.UUID(native_id(self.store, thread_id)))
            root = Path(os.environ.get("CLAUDE_CONFIG_DIR", Path.home() / ".claude")) / "projects"
            paths = list(root.glob("*/" + identity + ".jsonl"))
            if len(paths) != 1 or not current["turn_started_at"]:
                return None
            path = paths[0]
            if path.is_symlink() or path.stat().st_size > 64 * 1024 * 1024:
                return None
            before = path.stat()
            # Unlike usage accounting, partial native tails are unsafe here:
            # they may be a newer prompt or outstanding tool operation.
            entries = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
            after = path.stat()
            if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
                return None
            user = next((i for i in turn.get("items", []) if i.get("type") == "userMessage"), {})
            prompt = "\n".join(c.get("text", "") for c in user.get("content", []))
            matched = final = stopped = False
            for entry in entries:
                if not isinstance(entry, dict):
                    return None
                if entry.get("sessionId") != identity or entry.get("isSidechain"):
                    continue
                message = entry.get("message") or {}
                content = message.get("content", [])
                if entry.get("type") == "user" and (isinstance(content, str) or any(isinstance(c, dict) and c.get("type") == "text" for c in content)):
                    text = content if isinstance(content, str) else "\n".join(c.get("text", "") for c in content if isinstance(c, dict) and c.get("type") == "text")
                    stamp = datetime.fromisoformat(entry["timestamp"].replace("Z", "+00:00")).timestamp()
                    matched = bool(user.get("id") and entry.get("uuid") == user["id"] and prompt and text == prompt
                                   and stamp >= current["turn_started_at"] - 2)
                    final = stopped = False
                elif matched and entry.get("type") == "user":
                    final = stopped = False  # Tool results after Stop are not proof of idleness.
                elif matched and entry.get("type") in {"assistant", "api-request"}:
                    final = entry.get("type") == "assistant" and message.get("stop_reason") == "end_turn"
                    stopped = False
                elif matched and entry.get("subtype") == "stop_hook_summary":
                    stopped = bool(final and entry.get("preventedContinuation") is False
                                   and not entry.get("hookErrors") and not entry.get("stopReason"))
            if matched and final and stopped:
                return {**turn, "status": "completed", "error": None}
        except (OSError, ValueError, KeyError, TypeError):
            pass  # Missing or ambiguous proof leaves the failure gate intact.
        return None

    def recover(self, thread_id, expected_turn_id, requester, *, reason=None, execution_confirmed=False):
        """Explicit creator authorization for fresh work after a terminal turn.

        Never replay the previous prompt or reset uncertain wake attempts.
        The authorization and its reason are audited with the pause change.
        Historical inbox messages remain visible as context; the supervisor
        reviews them and supplies fresh instructions defining authorized work.
        """
        supplied_reason = reason
        reason = reason or "Creating orchestrator authorized fresh inbox work after inspecting the terminal turn."
        if not self.sessions.persistence.flush():
            raise CoordinationError("Conversation state is still being saved. Try again shortly.")
        with self.sessions._thread_lock(thread_id):
            detail = self.sessions.read(thread_id)
            turns = detail["thread"].get("turns", [])
            if detail["running"]:
                raise CoordinationError("Recovery refused: the conversation is running.")
            if not turns:
                raise CoordinationError("Recovery refused: the conversation has no recorded turn.")
            latest = turns[-1]
            if latest.get("id") != expected_turn_id:
                raise CoordinationError(f"Recovery refused: expected turn {expected_turn_id!r}, "
                                        f"but the latest turn is {latest.get('id')!r}.")
            if latest.get("status") not in {"failed", "interrupted", "completed"}:
                raise CoordinationError(f"Recovery refused: latest turn status is {latest.get('status')!r}; "
                                        "expected failed or interrupted.")
            with self.store._connection() as db:
                db.execute("BEGIN IMMEDIATE")
                from .supervision import authorizes
                if not authorizes(db, requester, thread_id):
                    raise CoordinationError("Only this app agent's current supervisor can recover it.")
                if self.store.threads.get(thread_id)["attention"] == "archived":
                    raise CoordinationError("Recovery cannot reopen a closed conversation.")
                if db.execute("SELECT 1 FROM sqlite_master WHERE name = 'thread_close_requests'").fetchone() and db.execute(
                        "SELECT 1 FROM thread_close_requests WHERE thread_id = ? AND status IN ('queued', 'closing')",
                        (thread_id,)).fetchone():
                    raise CoordinationError("The conversation has a pending close request.")
                if db.execute("SELECT 1 FROM browser_message_queue WHERE thread_id = ?", (thread_id,)).fetchone():
                    raise CoordinationError("Queued user input takes priority. Review it in the app before recovery.")
                wake = db.execute("SELECT * FROM browser_inbox_wake WHERE thread_id = ?", (thread_id,)).fetchone()
                if not wake or not wake["paused"]:
                    raise CoordinationError("Recovery refused: inbox wake is not paused.")
                if wake["dispatching"]:
                    raise CoordinationError("Recovery refused: an inbox wake is still dispatching; inspect its outcome first.")
                if wake["pause_kind"] != "failure":
                    raise CoordinationError(f"Recovery refused: pause kind {wake['pause_kind']!r} is uncertain; "
                                            "Stop or uncertain wake needs direct user input.")
                if latest.get("status") == "completed" and wake["reconciled_turn_id"] != expected_turn_id:
                    raise CoordinationError("Recovery refused: a completed turn has no recorded false-failure correction.")
                termination = latest.get("termination") or {}
                uncertain = (latest.get("status") == "interrupted"
                             or termination.get("execution") == "unknown"
                             or any(i.get("type") not in {"userMessage", "agentMessage", "reasoning", "plan"}
                                    and i.get("status") in {"inProgress", "unknown"}
                                    for i in latest.get("items", [])))
                if uncertain and not (execution_confirmed and supplied_reason):
                    raise CoordinationError("Native execution may continue after a terminal event. Inspect the native agent "
                                            "and tool outcomes, then use --confirm-stopped with --reason describing "
                                            "the evidence. Do not replay operations with unknown outcomes.")
                if not db.execute("""SELECT 1 FROM messages m
                        LEFT JOIN message_wake_attempts a ON a.message_id = m.id
                        WHERE m.recipient_session_id = ? AND m.delivered_at IS NULL
                        AND m.classification = 'action_required' AND m.suppressed_at IS NULL
                        AND a.message_id IS NULL AND m.thread_id NOT LIKE 'event:%'
                        AND m.id > ?""", (thread_id, wake["recovery_after_message_id"])).fetchone():
                    raise CoordinationError("Queue a fresh actionable continuation after reviewing the historical inbox. "
                                            "Earlier messages remain queued as context; state which work is authorized now; "
                                            "uncertain submissions are never replayed.")
                db.execute("""UPDATE browser_inbox_wake SET paused = 0, error = NULL,
                    pause_kind = NULL, recovery_turn_id = ?, paused_at = NULL,
                    reconciled_turn_id = NULL, recovery_after_message_id = 0 WHERE thread_id = ?""", (expected_turn_id, thread_id))
                db.execute("""INSERT INTO browser_wake_recoveries
                    (thread_id, turn_id, requester, reason, pause_kind, recovered_at, execution_confirmed)
                    VALUES (?, ?, ?, ?, ?, ?, ?)""",
                    (thread_id, expected_turn_id, requester, reason, wake["pause_kind"], self.store.clock(), int(execution_confirmed)))
            return {"session_id": thread_id, "resumed_after_turn_id": expected_turn_id, "state": "ready",
                    "resumed_by": requester, "reason": reason}

    def _eligible(self, db, thread_id, *, submitting=False):
        if self.stopped.is_set() or self.sessions.closed:
            return False
        if hasattr(self.sessions, "reviews") and not self.sessions.reviews.wake_allowed(db, thread_id):
            return False
        from .sidecars import discard_stale_messages
        discard_stale_messages(db, thread_id, self.store.clock())
        row = db.execute("""SELECT s.turn_active, t.attention,
                w.paused, w.dispatching, w.retry_at
            FROM browser_sessions b JOIN work_threads t ON t.thread_id = b.thread_id
            JOIN sessions s ON s.session_id = b.thread_id
            LEFT JOIN browser_inbox_wake w ON w.thread_id = b.thread_id
            WHERE b.thread_id = ?""", (thread_id,)).fetchone()
        if (not row or row["turn_active"] or row["paused"] or (row["dispatching"] and not submitting)):
            return False
        if row["retry_at"] and row["retry_at"] > self.store.clock():
            return False
        if row["attention"] == "archived" and not db.execute("""SELECT 1 FROM messages
                WHERE recipient_session_id = ? AND delivered_at IS NULL
                AND classification = 'action_required' AND thread_id NOT LIKE 'event:%'""", (thread_id,)).fetchone():
            # Stored subscriptions wait for explicit reopening. Avoid even
            # loading/unarchiving a cold provider conversation for these events.
            return False
        # User follow-ups, including paused ones, take priority over inbox work.
        if db.execute("SELECT 1 FROM browser_message_queue WHERE thread_id = ?", (thread_id,)).fetchone():
            return False
        if db.execute("SELECT 1 FROM sqlite_master WHERE name = 'thread_close_requests'").fetchone():
            if db.execute("""SELECT 1 FROM thread_close_requests WHERE thread_id = ?
                    AND status IN ('queued', 'closing')""", (thread_id,)).fetchone():
                return False
        return True

    def can_submit(self, thread_id):
        with self.store._connection() as db:
            return self._eligible(db, thread_id, submitting=True) and bool(db.execute("""
                SELECT 1 FROM message_wake_attempts a JOIN messages m ON m.id = a.message_id
                WHERE a.session_id = ? AND a.outcome = 'claimed'
                AND m.delivered_at IS NULL AND m.classification = 'action_required'
                AND (m.thread_id NOT LIKE 'event:%' OR EXISTS (
                    SELECT 1 FROM work_threads t WHERE t.thread_id = a.session_id AND t.attention != 'archived'))
                """, (thread_id,)).fetchone())

    def _claim(self, thread_id):
        with self.store._connection() as db:
            db.execute("BEGIN IMMEDIATE")
            if not self._eligible(db, thread_id):
                return []
            rows = db.execute("""SELECT m.id FROM messages m
                LEFT JOIN message_wake_attempts a ON a.message_id = m.id
                WHERE m.recipient_session_id = ? AND m.delivered_at IS NULL
                AND m.classification = 'action_required' AND a.message_id IS NULL
                AND (m.thread_id NOT LIKE 'event:%' OR EXISTS (
                    SELECT 1 FROM work_threads t WHERE t.thread_id = m.recipient_session_id AND t.attention != 'archived'))
                ORDER BY m.id""", (thread_id,)).fetchall()
            ids = [row[0] for row in rows]
            if hasattr(self.sessions, "reviews"):
                ids = self.sessions.reviews.message_ids(db, thread_id, ids)
            if ids:
                db.execute("""INSERT INTO browser_inbox_wake (thread_id, dispatching)
                    VALUES (?, 1) ON CONFLICT(thread_id) DO UPDATE SET dispatching = 1""", (thread_id,))
                db.executemany("""INSERT INTO message_wake_attempts
                    (message_id, session_id, attempted_at, outcome, detail)
                    VALUES (?, ?, ?, 'claimed', 'App inbox wake')""",
                    [(message_id, thread_id, self.store.clock()) for message_id in ids])
            return ids

    def process_once(self):
        # Read just pending recipients, not conversation histories, on each tick.
        with self.store._connection() as db:
            rows = db.execute("""SELECT DISTINCT b.thread_id, b.cwd FROM messages m
                JOIN browser_sessions b ON b.thread_id = m.recipient_session_id
                LEFT JOIN message_wake_attempts a ON a.message_id = m.id
                WHERE m.delivered_at IS NULL AND m.classification = 'action_required'
                AND a.message_id IS NULL""").fetchall()
        for row in rows:
            if self.stopped.is_set() or self.sessions.closed:
                return
            if not matches_workspace(row["cwd"], self.sessions.cwd):
                continue
            try:
                self._dispatch(row["thread_id"])
            except Exception:
                logging.getLogger(__name__).exception("App inbox wake failed for %s", row["thread_id"])

    def _dispatch(self, thread_id):
        from .codex_app_server import BrowserBusyError, BrowserNotSubmittedError
        sessions = self.sessions
        with sessions._thread_lock(thread_id):
            self._reconcile_pause(thread_id)
            with self.store._connection() as db:
                if not self._eligible(db, thread_id):
                    return
            with sessions.lock:
                if thread_id in sessions.active:
                    return
            # Resuming a cold conversation and reading provider status can fail
            # before a turn is sent. Pause instead of repeatedly launching it.
            try:
                detail = sessions.read(thread_id)
            except Exception as exc:
                self._not_submitted(thread_id, exc)
                return
            if detail["running"]:
                return
            turns = detail["thread"].get("turns", [])
            if turns and turns[-1].get("status") in {"interrupted", "failed"}:
                with self.store._connection() as db:
                    recovery = db.execute("SELECT recovery_turn_id FROM browser_inbox_wake WHERE thread_id = ?",
                                          (thread_id,)).fetchone()
                if not (recovery and recovery[0] == turns[-1].get("id")):
                    latest = turns[-1]
                    deliberate = ((latest.get("termination") or {}).get("origin") == "user"
                                  or self.store.threads.stop_requested(thread_id, latest.get("id")))
                    self.pause(thread_id, "The last turn stopped or failed. Send a message to continue.",
                               kind="stop" if deliberate else "failure")
                    if not deliberate:
                        notify_agent_failure(self.store, thread_id, event_key=["turn", latest.get("id")],
                                             stage="turn", turn_id=latest.get("id"), error=latest.get("error") or
                                             "The provider interrupted this turn. Native execution and tool outcomes must be inspected.")
                    return
            ids = self._claim(thread_id)
            if not ids:
                return
            try:
                prompt = sessions.reviews.wake_prompt(thread_id, ids) if hasattr(sessions, "reviews") else None
                result = sessions.send(thread_id, {"message": prompt or WAKE_PROMPT}, start_only=True, automatic=True)
                turn_id = result.get("turn", {}).get("id")
                if turn_id:
                    with self.store._connection() as db:
                        db.executemany("UPDATE messages SET wake_turn_id = ? WHERE id = ? AND recipient_session_id = ?",
                                       [(turn_id, message_id, thread_id) for message_id in ids])
                        if hasattr(sessions, "reviews"):
                            sessions.reviews.bind(db, thread_id, turn_id)
            except BrowserBusyError:
                # Rejected before RPC: another turn, Stop, closure, or delivery
                # won the race. Leave undelivered work eligible for a later tick.
                with self.store._connection() as db:
                    db.executemany("DELETE FROM message_wake_attempts WHERE message_id = ? AND outcome = 'claimed'",
                                   [(message_id,) for message_id in ids])
            except BrowserNotSubmittedError as exc:
                with self.store._connection() as db:
                    db.executemany("DELETE FROM message_wake_attempts WHERE message_id = ? AND outcome = 'claimed'",
                                   [(message_id,) for message_id in ids])
                self._not_submitted(thread_id, exc.__cause__ or exc)
            except Exception as exc:
                with self.store._connection() as db:
                    stopped = db.execute("""SELECT r.turn_id FROM turn_stop_requests r
                        JOIN work_threads t ON t.thread_id = r.thread_id AND t.turn_id = r.turn_id
                        WHERE r.thread_id = ? AND r.turn_id IS NOT ?""",
                        (thread_id, turns[-1].get("id") if turns else None)).fetchone()
                    if stopped:
                        # Native start was observed before its response failed.
                        # Bind that accepted turn so subscriptions can report Stop.
                        db.executemany("UPDATE messages SET wake_turn_id = ? WHERE id = ? AND recipient_session_id = ?",
                                       [(stopped["turn_id"], message_id, thread_id) for message_id in ids])
                if stopped:
                    self.store.complete_wake_attempts(thread_id, ids, outcome="sent", detail="Accepted turn stopped by the user.")
                    return
                self.store.complete_wake_attempts(thread_id, ids, outcome="failed", detail=str(exc))
                self.pause(thread_id, "Inbox wake may have started; send a message to continue. " + str(exc))
                self._report_failure(thread_id, str(exc))
            else:
                self.store.complete_wake_attempts(thread_id, ids, outcome="sent", detail=WAKE_PROMPT)
                with self.store._connection() as db:
                    db.execute("UPDATE browser_inbox_wake SET retry_count = 0, retry_at = NULL WHERE thread_id = ?", (thread_id,))
            finally:
                with self.store._connection() as db:
                    db.execute("UPDATE browser_inbox_wake SET dispatching = 0 WHERE thread_id = ?", (thread_id,))

    def _report_failure(self, thread_id, error):
        self.sessions.persistence.submit(lambda: self._persist_failure(thread_id, error))

    def _persist_failure(self, thread_id, error):
        with self.store._connection() as db:
            ids = [row[0] for row in db.execute("""SELECT id FROM messages
                WHERE recipient_session_id = ? AND delivered_at IS NULL
                AND classification = 'action_required' ORDER BY id""", (thread_id,))]
        notify_agent_failure(self.store, thread_id, event_key=["wake", ids], stage="wake", error=error)

    def start(self):
        if self.worker is None:
            self.worker = threading.Thread(target=self._run, name="browser-inbox-wake", daemon=True)
            self.worker.start()

    def _run(self):
        while not self.stopped.is_set() and not self.sessions.closed:
            try:
                self.process_once()
            except Exception:
                logging.getLogger(__name__).exception("App inbox wake worker failed")
            self.stopped.wait(.5)

    def close(self):
        self.stopped.set()
        if self.worker is not None:
            self.worker.join(timeout=5)
